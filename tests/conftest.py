import os
import uuid
from pathlib import Path

import pytest

from cpss.core import Settings
from cpss.repository import Repository

FIXTURES = Path(__file__).parent / "fixtures"


@pytest.fixture
def fixtures():
    return FIXTURES


@pytest.fixture
def repo(tmp_path):
    if os.getenv("CPSS_TEST_MONGO") != "1":
        pytest.skip("real MongoDB tests require CPSS_TEST_MONGO=1")
    name = "cpss_test_" + uuid.uuid4().hex
    repository = Repository(Settings(uri=os.getenv("CPSS_TEST_MONGODB_URI", "mongodb://127.0.0.1:27017/"),
                                     database=name, cache_dir=tmp_path / "cache"))
    try:
        repository.client.admin.command("ping")
        repository.bootstrap()
        yield repository
    finally:
        # Delete only the exact disposable database generated by this fixture.
        if repository.db.name == name and name.startswith("cpss_test_"):
            repository.client.drop_database(name)
        repository.close()

